// 中央パネル (.housing-browse-col-center) 用に「倍率を含むトークン」を再宣言するブロックを生成する。
// 理由: --housing-x: calc(Npx * var(--housing-scale)) は宣言した要素で計算されて子に継承されるため、
//       中央だけ倍率を変えるには中央パネルの要素で同じトークンを宣言し直す必要がある。
// 使い方: convert.mjs の後に node scripts/housing-scale/center-tokens.mjs  (冪等・マーカー間を置換)
import fs from 'node:fs';

const FILE = new URL('../../src/styles/housing.css', import.meta.url);
let css = fs.readFileSync(FILE, 'utf8');
const BEGIN = '/* BEGIN housing-center-tokens (generated by scripts/housing-scale/center-tokens.mjs) */';
const END = '/* END housing-center-tokens */';
const bi = css.indexOf(BEGIN);
if (bi >= 0) css = css.slice(0, bi).trimEnd() + '\n';

// 1) 主トークンブロック (先頭の .housing-workspace, ... { ... }) と C 案の文字上書きブロックから宣言を集める
const strip = (t) => t.replace(/\/\*[\s\S]*?\*\//g, '');
const mainStart = css.indexOf('.housing-workspace,\n.housing-panel-modal-backdrop');
const mainEnd = css.indexOf('\n}\n', mainStart);
const decls = new Map();
const collect = (text) => {
  for (const m of strip(text).matchAll(/(--housing-[\w-]+)\s*:\s*([^;]+);/g)) decls.set(m[1], m[2].trim());
};
collect(css.slice(mainStart, mainEnd));
// C 案の文字トークン上書き
const cStart = css.indexOf('html:root .housing-workspace,');
collect(css.slice(cStart, css.indexOf('}', cStart)));

// 2) 倍率を含む / それを参照するトークンの閉包
const set = new Set();
for (const [k, v] of decls) if (v.includes('--housing-scale)')) set.add(k);
let grew = true;
while (grew) {
  grew = false;
  for (const [k, v] of decls) {
    if (set.has(k)) continue;
    for (const m of v.matchAll(/var\((--housing-[\w-]+)/g)) {
      if (set.has(m[1])) { set.add(k); grew = true; break; }
    }
  }
}
const lines = [...decls].filter(([k]) => set.has(k)).map(([k, v]) => `    ${k}: ${v};`);
const block = `${BEGIN}\n@media (min-width: 768px) {\n  html:root .housing-browse-col-center {\n${lines.join('\n')}\n  }\n}\n${END}\n`;
fs.writeFileSync(FILE, css + '\n' + block);
console.log('center tokens:', lines.length);
